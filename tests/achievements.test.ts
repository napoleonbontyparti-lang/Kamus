import { addCard, listDecks, setMark, logSession, sektiBalance, studyQueue, review, cardsInDeck, spendSekti, exportBackup, importBackup } from "../src/lib/userdb";
import { getAchievements, claim, refreshAchievements, claimableCount } from "../src/lib/achievements";
import { bumpCounter } from "../src/lib/settings";
const assert = (c: unknown, m: string) => { if (!c) { console.error("FAIL", m); process.exit(1); } console.log("ok ", m); };
const get = (id: string) => getAchievements().find((a) => a.id === id)!;

assert(claimableCount(getAchievements()) === 0 && sektiBalance() === 0, "старт: ничего не получено, 0 Секти");
const deck = listDecks()[0];
for (let i = 0; i < 12; i++) addCard({ deckId: deck.id, front: `kata${i}`, back: `слово ${i}`, root: "kata" });
refreshAchievements();
const pk = get("pengumpul-kata");
assert(pk.reached === 1 && pk.claimable === 5 && pk.target === 50, "Pengumpul Kata: уровень 1, можно забрать 5");
assert(claim("pengumpul-kata") === 5 && sektiBalance() === 5, "забрали +5 Секти");
assert(claim("pengumpul-kata") === 0 && sektiBalance() === 5, "повторно не выдаётся");
setMark(cardsInDeck(deck.id).map((c) => c.id), 1);
logSession(deck.id, "choice-ir", 6, 6, 0);
const q = studyQueue(deck.id);
for (const c of q) review(c, 3);
bumpCounter("ocr");
refreshAchievements();
assert(get("hafal-luar-kepala").claimable === 5, "Hafal Luar Kepala: 12 выученных → +5");
assert(get("tanpa-cela").claimable === 5 && get("latihan-terus").claimable === 3, "сессия без ошибок → Tanpa Cela и Latihan Terus");
assert(get("mata-elang").claimable === 5, "поиск по фото → Mata Elang");
assert(get("api-biru").reached === 0 && get("api-biru").value === 1, "серия 1 день — Api Biru ещё нет");
const before = sektiBalance();
["hafal-luar-kepala", "tanpa-cela", "latihan-terus", "mata-elang"].forEach(claim);
assert(sektiBalance() === before + 18, "получено ещё 18 Секти");
assert(spendSekti(10, "test") && sektiBalance() === before + 8 && !spendSekti(999, "x"), "тратить можно, но не больше баланса");
const json = exportBackup();
importBackup(json); refreshAchievements();
assert(sektiBalance() === before + 8 && get("pengumpul-kata").claimed === 1, "Секти и полученные уровни в резервной копии");
console.log("всего Секти:", sektiBalance());
