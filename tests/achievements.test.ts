import { markVisit, addCard, listDecks, setMark, logSession, sektiBalance, studyQueue, review, cardsInDeck, spendSekti, exportBackup, importBackup } from "../src/lib/userdb";
import { getAchievements, claim, refreshAchievements, claimableCount } from "../src/lib/achievements";
import { bumpCounter } from "../src/lib/settings";
const assert = (c: unknown, m: string) => { if (!c) { console.error("FAIL", m); process.exit(1); } console.log("ok ", m); };
const get = (id: string) => getAchievements().find((a) => a.id === id)!;

assert(claimableCount(getAchievements()) === 0 && sektiBalance() === 0, "старт: ничего не получено, 0 Секти");
const deck = listDecks()[0];
for (let i = 0; i < 12; i++) addCard({ deckId: deck.id, front: `kata${i}`, back: `слово ${i}`, root: "kata" });
refreshAchievements();
const pk = get("pengumpul-kata");
assert(pk.reached === 1 && pk.claimable === 10 && pk.target === 50, "Pengumpul Kata: уровень 1, можно забрать 10");
assert(claim("pengumpul-kata") === 10 && sektiBalance() === 10, "забрали +10 Секти");
assert(claim("pengumpul-kata") === 0 && sektiBalance() === 10, "повторно не выдаётся");
setMark(cardsInDeck(deck.id).map((c) => c.id), 1);
logSession(deck.id, "choice-ir", 6, 6, 0);
const q = studyQueue(deck.id);
for (const c of q) review(c, 3);
bumpCounter("ocr");
refreshAchievements();
assert(get("hafal-luar-kepala").claimable === 10, "Hafal Luar Kepala: 12 выученных → +10");
assert(get("tanpa-cela").claimable === 10, "сессия без ошибок → Tanpa Cela +10");
markVisit(); refreshAchievements();
assert(get("rajin-datang").value === 1 && get("rajin-datang").claimable === 0, "Rajin Datang: 1 день из 3");
assert(get("mata-elang").claimable === 10, "поиск по фото → Mata Elang +10");
assert(get("api-biru").reached === 0 && get("api-biru").value === 1, "серия 1 день — Api Biru ещё нет");
const before = sektiBalance();
["hafal-luar-kepala", "tanpa-cela", "mata-elang"].forEach(claim);
assert(sektiBalance() === before + 30, "получено ещё 30 Секти");
assert(spendSekti(10, "test") && sektiBalance() === before + 20 && !spendSekti(999, "x"), "тратить можно, но не больше баланса");
const json = exportBackup();
importBackup(json); refreshAchievements();
assert(sektiBalance() === before + 20 && get("pengumpul-kata").claimed === 1, "Секти и полученные уровни в резервной копии");
console.log("всего Секти:", sektiBalance());
// все 5 уровней дают 10+20+30+50+100
import { TIER_REWARDS, ACHIEVEMENTS } from "../src/lib/achievements";
assert(TIER_REWARDS.join() === "10,20,30,50,100" && ACHIEVEMENTS.every((a) => a.tiers.length === 5 && a.caption.includes("{n}")), "у всех достижений 5 уровней и индонезийская подпись");
